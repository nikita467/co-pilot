/** Итоговый скор: RICE + compliance + стратегия. */
export const taskScore = (t: Task) => {
  const rice = (t.reach * t.impactScore * t.confidence) / Math.max(t.effort, 0.5);
  const riceNorm = Math.min(rice / 300, 60); // 0..60
  return Math.round(riceNorm + t.compliance * 2.5 + t.strategy * 1.5);
};

